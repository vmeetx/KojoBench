"""
Claude-as-proxy eval.
Reads Task{N}_claude.kojo files (generated by Claude reading ONLY
system prompt + queries — no GT code was read before generation).
Renders each, scores NSS + KCSS, shows live UI window.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))

from eval_engine import TASKS, score_task, render_code, show_window

HERE      = Path(__file__).parent
KOJO_DIR  = HERE / "claude"
OUT_DIR   = HERE / "claude_rendered"
OUT_DIR.mkdir(exist_ok=True)

def main():
    print("[Claude Proxy] Rendering + scoring (query+system-prompt only input)\n")
    results = []

    for t in TASKS:
        kojo_file = KOJO_DIR / f"task{t}.kojo"
        if not kojo_file.exists():
            print(f"  Task {t}: missing — skipping")
            results.append(score_task(t, ""))
            continue

        code = kojo_file.read_text(encoding="utf-8")
        print(f"  Task {t}: rendering...", end=" ", flush=True)
        rendered = render_code(t, code, OUT_DIR)
        print("ok" if rendered else "FAILED")

        r = score_task(t, code, rendered)
        nss_str = f"NSS={r['nss']*100:.0f}%" if r["nss"] is not None else "NSS=n/a"
        print(f"    KCSS={r['kcss']*100:.0f}%  {nss_str}  lines={r['lines']}")
        results.append(r)

    avg_k = sum(r["kcss"] for r in results) / len(results)
    nss_v = [r["nss"] for r in results if r["nss"] is not None]
    avg_n = sum(nss_v) / len(nss_v) if nss_v else None
    print(f"\n  Avg KCSS: {avg_k*100:.0f}%  Avg NSS: {avg_n*100:.1f}%" if avg_n else f"\n  Avg KCSS: {avg_k*100:.0f}%")

    show_window("Claude Sonnet 4.6  —  proxy (system prompt + query only)", results, accent="#a78bfa")

if __name__ == "__main__":
    main()
